test('19/20 OTP resend timer and 3-resend limit', async ({ page }) => {
  await start(page)
  await enterEmail(page, 'existing@jahez.net')
  const resend = phone(page).getByTestId('otp-resend')
  await expect(resend).toContainText(/Resend in (1:00|0:5\d)/)
  await expect(phone(page).getByRole('button', { name: 'Resend code' })).toHaveCount(0)
  for (let i = 1; i <= 3; i++) {
    await page.clock.fastForward(60_000)
    await phone(page).getByRole('button', { name: 'Resend code' }).click()
    await expect(activity(page)).toContainText(`Resend ${i} of 3`)
    if (i < 3) {
      await expect(resend).toContainText(/Resend in (1:00|0:5\d)/)
      await expect(resend).toContainText(`${3 - i} resend${3 - i === 1 ? '' : 's'} left`)
    }
  }
  await expect(resend).toContainText('Resend limit reached')
  await page.clock.fastForward(120_000)
  await expect(phone(page).getByRole('button', { name: 'Resend code' })).toHaveCount(0)
  await expect(activity(page)).toContainText('Resend limit reached')
  await snap(page, 'shots/t-resend-limit.png')
  await typeOtp(page, '1234')
  await expect(phone(page).getByTestId('current-brand')).toBeVisible()
})

