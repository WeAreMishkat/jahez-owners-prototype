import { expect, test, type Page } from '@playwright/test'

const phone = (p: Page) => p.getByTestId('phone')
const activity = (p: Page) => p.getByTestId('activity')
const btn = (p: Page, name: string | RegExp) => phone(p).getByRole('button', { name, exact: typeof name === 'string' })

async function snap(page: Page, path: string) {
  await page.waitForTimeout(500)
  await page.screenshot({ path })
}

async function start(page: Page) {
  await page.clock.install()
  await page.goto('./')
  await expect(phone(page).getByRole('heading', { name: 'Welcome to Jahez for Owners' })).toBeVisible()
}

async function enterEmail(page: Page, email: string) {
  await phone(page).getByLabel('Email').fill(email)
  await btn(page, 'Continue').click()
}

async function typeOtp(page: Page, code: string) {
  await phone(page).getByLabel('Digit 1').focus()
  await page.keyboard.type(code)
}

async function toNationalId(page: Page, email: string) {
  await enterEmail(page, email)
  await expect(phone(page).getByRole('heading', { name: 'Let’s get you set up' })).toBeVisible()
  await phone(page).getByRole('radio', { name: /I already have a restaurant/ }).click()
  await btn(page, 'Continue').click()
  await expect(phone(page).getByRole('heading', { name: 'Verify your National ID' })).toBeVisible()
}

async function submitId(page: Page, id: string) {
  await phone(page).getByRole('textbox', { name: 'National ID' }).fill(id)
  await phone(page).getByText('I agree that Jahez may use').click()
  await btn(page, 'Continue').click()
}

async function toNafath(page: Page, email = 'abdullah@jahez.net', id = '1222222222') {
  await toNationalId(page, email)
  await submitId(page, id)
  await expect(phone(page).getByRole('heading', { name: 'Verify your identity' })).toBeVisible()
}

